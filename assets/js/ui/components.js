/*
 * TrueFrame — reusable UI components: gauge, toast, tooltip, clipboard, lightbox,
 * and the forensic comparison viewer (slider / overlay / side-by-side + magnifier).
 */
(function (root) {
  'use strict';
  const TF = root.TrueFrame;
  const U = TF.util;
  const I = root.TFIcon;
  const UI = (root.TFUI = root.TFUI || {});
  const esc = U.escapeHtml;
  UI.$ = (s, el) => (el || document).querySelector(s);
  UI.$$ = (s, el) => Array.from((el || document).querySelectorAll(s));
  UI.esc = esc;
  UI.reducedMotion = () => window.matchMedia && matchMedia('(prefers-reduced-motion: reduce)').matches;

  UI.hydrateIcons = (rootEl) => {
    UI.$$('[data-icon]', rootEl).forEach((el) => {
      if (!el.querySelector('svg')) el.insertAdjacentHTML('afterbegin', I(el.dataset.icon));
    });
  };

  // ------------------------------------------------------------------ gauge
  const R = 60;
  const CIRC = 2 * Math.PI * R;
  UI.gaugeHTML = (id, size, label) =>
    `<div class="gauge ${size || ''}" id="${id}" role="img" aria-label="AI likelihood not known yet"><svg viewBox="0 0 148 148"><circle class="gauge-track" cx="74" cy="74" r="${R}" fill="none" stroke-width="12"/><circle class="gauge-fill" cx="74" cy="74" r="${R}" fill="none" stroke-width="12" stroke-linecap="round" stroke-dasharray="${CIRC.toFixed(2)}" stroke-dashoffset="${CIRC.toFixed(2)}"/></svg><div class="gauge-center"><span class="gauge-value">–</span><span class="gauge-label">${esc(label)}</span></div></div>`;

  UI.toneOf = (p) => (p >= 0.65 ? 'ai' : p <= 0.35 ? 'real' : 'uncertain');

  UI.gaugeSet = (el, p, tone, noun) => {
    if (!el) return;
    const fill = el.querySelector('.gauge-fill');
    const val = el.querySelector('.gauge-value');
    el.dataset.tone = tone || UI.toneOf(p);
    requestAnimationFrame(() => (fill.style.strokeDashoffset = (CIRC * (1 - p)).toFixed(2)));
    const from = el._v == null ? 0 : el._v;
    const to = Math.round(p * 100);
    el._v = to;
    if (to !== from && !UI.reducedMotion()) {
      el.classList.remove('bump');
      void el.offsetWidth;
      el.classList.add('bump');
    }
    el.setAttribute('aria-label', `${to}% likelihood that this ${noun || 'file'} was generated by AI`);
    cancelAnimationFrame(el._raf);
    if (UI.reducedMotion()) {
      val.innerHTML = to + '<small>%</small>';
      return;
    }
    const t0 = performance.now();
    const dur = 800;
    const tick = (t) => {
      // rAF timestamps can precede t0 (they mark the frame start), so clamp at 0.
      const k = U.clamp((t - t0) / dur, 0, 1);
      const e = 1 - Math.pow(1 - k, 3);
      val.innerHTML = Math.round(from + (to - from) * e) + '<small>%</small>';
      if (k < 1) el._raf = requestAnimationFrame(tick);
    };
    el._raf = requestAnimationFrame(tick);
  };

  // ------------------------------------------------------------------ toast, tooltip, copy
  let toastTimer = null;
  UI.toast = (msg) => {
    const t = UI.$('#toast');
    t.textContent = msg;
    t.hidden = false;
    t.style.animation = 'none';
    void t.offsetWidth;
    t.style.animation = '';
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => (t.hidden = true), 3200);
  };

  UI.initTooltip = () => {
    const tip = UI.$('#tooltip');
    let current = null;
    const place = (x, y) => {
      const pad = 14;
      const r = tip.getBoundingClientRect();
      let left = x + pad;
      let top = y + pad;
      if (left + r.width > window.innerWidth - 8) left = x - r.width - pad;
      if (top + r.height > window.innerHeight - 8) top = y - r.height - pad;
      tip.style.left = Math.max(8, left) + 'px';
      tip.style.top = Math.max(8, top) + 'px';
    };
    document.addEventListener('pointermove', (e) => {
      const el = e.target.closest && e.target.closest('[data-tip]');
      if (!el || e.pointerType === 'touch') {
        tip.hidden = true;
        current = null;
        return;
      }
      if (el !== current) {
        tip.textContent = el.getAttribute('data-tip');
        current = el;
      }
      tip.hidden = false;
      place(e.clientX, e.clientY);
    });
    document.addEventListener('focusin', (e) => {
      const el = e.target.closest && e.target.closest('[data-tip]');
      if (!el) return;
      const r = el.getBoundingClientRect();
      tip.textContent = el.getAttribute('data-tip');
      tip.hidden = false;
      place(r.left, r.bottom);
    });
    document.addEventListener('focusout', () => (tip.hidden = true));
    window.addEventListener('scroll', () => (tip.hidden = true), { passive: true });
  };

  UI.copy = async (text, label) => {
    try {
      await navigator.clipboard.writeText(text);
    } catch (e) {
      const ta = document.createElement('textarea');
      ta.value = text;
      ta.style.position = 'fixed';
      ta.style.opacity = '0';
      document.body.appendChild(ta);
      ta.select();
      try {
        document.execCommand('copy');
      } catch (err) {
        /* clipboard unavailable */
      }
      ta.remove();
    }
    UI.toast(label || 'Copied to clipboard');
  };

  // ------------------------------------------------------------------ lightbox
  UI.lightbox = (src, alt) => {
    const lb = UI.$('#lightbox');
    const img = lb.querySelector('img');
    img.src = src;
    img.alt = alt || '';
    lb.hidden = false;
    document.body.classList.add('no-scroll');
    const close = () => {
      lb.hidden = true;
      document.body.classList.remove('no-scroll');
      document.removeEventListener('keydown', onKey);
    };
    const onKey = (e) => {
      if (e.key === 'Escape') close();
    };
    lb.onclick = close;
    document.addEventListener('keydown', onKey);
    lb.querySelector('.icon-btn').focus();
  };

  // ------------------------------------------------------------------ comparison viewer
  /**
   * host: element; o: { base, baseLabel, top?, topLabel?, aspect, mode: slider|overlay|side, lens }
   * Returns { set(patch) }.
   */
  UI.viewer = function (host, o) {
    const st = Object.assign({ mode: 'slider', pos: 50, opacity: 0.75, lens: false, maxH: 520 }, o);
    let v = null;

    function apply() {
      if (!v) return;
      const top = v.querySelector('.v-top');
      const handle = v.querySelector('.v-handle');
      if (top) {
        if (st.mode === 'slider') {
          top.style.clipPath = `inset(0 0 0 ${st.pos}%)`;
          top.style.opacity = 1;
        } else {
          top.style.clipPath = 'none';
          top.style.opacity = st.opacity;
        }
      }
      if (handle) {
        handle.style.left = st.pos + '%';
        handle.setAttribute('aria-valuenow', String(Math.round(st.pos)));
      }
    }

    function render() {
      if (st.top && st.mode === 'side') {
        host.innerHTML = `<div class="side-by-side"><figure><img src="${st.base}" alt="${esc(st.baseLabel)}"><figcaption>${esc(st.baseLabel)}</figcaption></figure><figure><img src="${st.top}" alt="${esc(st.topLabel)}"><figcaption>${esc(st.topLabel)}</figcaption></figure></div>`;
        v = null;
        return;
      }
      const mode = st.top ? st.mode : 'single';
      const width = `min(100%, ${Math.round(st.maxH * st.aspect)}px)`;
      host.innerHTML = `<div class="viewer mode-${mode}${st.lens ? ' has-lens' : ''}" style="width:${width};aspect-ratio:${st.aspect}">
        <img class="v-base" src="${st.base}" alt="${esc(st.baseLabel)}">
        ${st.top ? `<div class="v-top"><img src="${st.top}" alt="${esc(st.topLabel)}"></div>` : ''}
        ${mode === 'slider' ? `<div class="v-handle" role="slider" tabindex="0" aria-label="Comparison divider: ${esc(st.baseLabel)} on the left, ${esc(st.topLabel)} on the right" aria-valuemin="0" aria-valuemax="100"><span class="v-knob">${I('arrows')}</span></div>` : ''}
        ${mode === 'slider' ? `<span class="v-tag v-tag-l">${esc(st.baseLabel)}</span><span class="v-tag v-tag-r">${esc(st.topLabel)}</span>` : ''}
        ${mode === 'overlay' ? `<span class="v-tag v-tag-l">${esc(st.topLabel)} over ${esc(st.baseLabel.toLowerCase())}</span>` : ''}
        <div class="v-lens" hidden></div>
      </div>`;
      v = host.querySelector('.viewer');
      apply();
      bind();
    }

    function bind() {
      const lens = v.querySelector('.v-lens');
      const handle = v.querySelector('.v-handle');
      let dragging = false;
      const frac = (e) => {
        const r = v.getBoundingClientRect();
        return { x: U.clamp((e.clientX - r.left) / r.width, 0, 1), y: U.clamp((e.clientY - r.top) / r.height, 0, 1), r };
      };
      const updateLens = (e) => {
        if (!st.lens) return;
        const { x, y, r } = frac(e);
        let src = st.base;
        if (st.top && st.mode === 'slider' && x * 100 > st.pos) src = st.top;
        if (st.top && st.mode === 'overlay' && st.opacity >= 0.5) src = st.top;
        const Z = 3;
        const rad = 82;
        lens.hidden = false;
        lens.style.left = x * r.width + 'px';
        lens.style.top = y * r.height + 'px';
        lens.style.backgroundImage = `url("${src}")`;
        lens.style.backgroundSize = `${r.width * Z}px ${r.height * Z}px`;
        lens.style.backgroundPosition = `${-(x * r.width * Z - rad)}px ${-(y * r.height * Z - rad)}px`;
      };
      v.addEventListener('pointerdown', (e) => {
        if (st.mode !== 'slider' || !st.top) return;
        dragging = true;
        v.classList.add('is-dragging');
        try {
          v.setPointerCapture(e.pointerId);
        } catch (err) {
          /* not an active pointer (e.g. synthetic event) — dragging still works inside the viewer */
        }
        st.pos = frac(e).x * 100;
        apply();
      });
      v.addEventListener('pointermove', (e) => {
        if (dragging) {
          st.pos = frac(e).x * 100;
          apply();
        }
        updateLens(e);
      });
      const end = () => {
        dragging = false;
        v.classList.remove('is-dragging');
      };
      v.addEventListener('pointerup', end);
      v.addEventListener('pointercancel', end);
      v.addEventListener('pointerleave', () => {
        if (lens) lens.hidden = true;
      });
      if (handle) {
        handle.addEventListener('keydown', (e) => {
          const step = e.shiftKey ? 10 : 2;
          if (e.key === 'ArrowLeft' || e.key === 'ArrowDown') st.pos = Math.max(0, st.pos - step);
          else if (e.key === 'ArrowRight' || e.key === 'ArrowUp') st.pos = Math.min(100, st.pos + step);
          else if (e.key === 'Home') st.pos = 0;
          else if (e.key === 'End') st.pos = 100;
          else return;
          e.preventDefault();
          apply();
        });
      }
    }

    render();
    return {
      set(patch) {
        const needsRender = ['mode', 'top', 'base', 'lens', 'topLabel', 'baseLabel', 'aspect'].some((k) => k in patch && patch[k] !== st[k]);
        Object.assign(st, patch);
        if (needsRender) render();
        else apply();
      },
      state: st,
    };
  };
})(window);
